    fun getHairstyleById(id: String): Hairstyle? = allHairstyles.find { it.id == id }

    fun getRecommendedForFace(faceShape: FaceShape, gender: HairGender? = null): List<Hairstyle> {
        return allHairstyles.filter { style ->
            val matchesGender = gender == null || gender == HairGender.UNISEX || style.gender == gender || style.gender == HairGender.UNISEX
            val matchesFace = style.recommendedFaceShapes.contains(faceShape)
            matchesGender && matchesFace
        }.sortedByDescending { it.popularityScore }
    }
